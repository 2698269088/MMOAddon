    /**
     * Generic rewriter that replaces Entity.teleport(Location) with Entity.teleportAsync(Location)
     * when the returned boolean is immediately discarded (POP). On Folia, synchronous teleport is
     * not allowed from region threads, while teleportAsync works everywhere. If the boolean return
     * value is used (no POP), the original teleport call is kept to avoid breaking control flow.
     */
    private static class EntityTeleportRewriter extends MethodVisitor {

        private static final String ENTITY_PACKAGE = "org/bukkit/entity/";
        private static final String LOCATION_CLASS = "org/bukkit/Location";
        private static final String TELEPORT_ASYNC_DESC = "(L" + LOCATION_CLASS + ";)Ljava/util/concurrent/CompletableFuture;";

        private boolean pendingTeleport = false;
        private int pendingOpcode;
        private String pendingOwner;
        private String pendingName;
        private String pendingDescriptor;
        private boolean pendingIsInterface;

        public EntityTeleportRewriter(MethodVisitor mv) {
            super(Opcodes.ASM9, mv);
        }

        @Override
        public void visitMethodInsn(int opcode, String owner, String name, String descriptor, boolean isInterface) {
            flushPending();
            if ((opcode == Opcodes.INVOKEVIRTUAL || opcode == Opcodes.INVOKEINTERFACE)
                    && owner != null && owner.startsWith(ENTITY_PACKAGE)
                    && "teleport".equals(name)
                    && ("(L" + LOCATION_CLASS + ";)Z").equals(descriptor)) {
                pendingTeleport = true;
                pendingOpcode = opcode;
                pendingOwner = owner;
                pendingName = name;
                pendingDescriptor = descriptor;
                pendingIsInterface = isInterface;
                return;
            }
            super.visitMethodInsn(opcode, owner, name, descriptor, isInterface);
        }

        @Override
        public void visitInsn(int opcode) {
            if (pendingTeleport) {
                pendingTeleport = false;
                if (opcode == Opcodes.POP) {
                    // Replace teleport with teleportAsync; the original POP discards the returned CompletableFuture.
                    super.visitMethodInsn(Opcodes.INVOKEINTERFACE, pendingOwner, "teleportAsync",
                            TELEPORT_ASYNC_DESC, true);
                    super.visitInsn(opcode);
                    return;
                }
                // The return value is actually used; keep the original teleport call.
                super.visitMethodInsn(pendingOpcode, pendingOwner, pendingName, pendingDescriptor, pendingIsInterface);
                super.visitInsn(opcode);
                return;
            }
            super.visitInsn(opcode);
        }

        @Override public void visitIntInsn(int opcode, int operand) { flushPending(); super.visitIntInsn(opcode, operand); }
        @Override public void visitVarInsn(int opcode, int varIndex) { flushPending(); super.visitVarInsn(opcode, varIndex); }
        @Override public void visitTypeInsn(int opcode, String type) { flushPending(); super.visitTypeInsn(opcode, type); }
        @Override public void visitFieldInsn(int opcode, String owner, String name, String descriptor) { flushPending(); super.visitFieldInsn(opcode, owner, name, descriptor); }
        @Override public void visitInvokeDynamicInsn(String name, String descriptor, Handle bootstrapMethodHandle, Object... bootstrapMethodArguments) { flushPending(); super.visitInvokeDynamicInsn(name, descriptor, bootstrapMethodHandle, bootstrapMethodArguments); }
        @Override public void visitJumpInsn(int opcode, Label label) { flushPending(); super.visitJumpInsn(opcode, label); }
        @Override public void visitLabel(Label label) { flushPending(); super.visitLabel(label); }
        @Override public void visitLdcInsn(Object value) { flushPending(); super.visitLdcInsn(value); }
        @Override public void visitIincInsn(int varIndex, int increment) { flushPending(); super.visitIincInsn(varIndex, increment); }
        @Override public void visitTableSwitchInsn(int min, int max, Label dflt, Label... labels) { flushPending(); super.visitTableSwitchInsn(min, max, dflt, labels); }
        @Override public void visitLookupSwitchInsn(Label dflt, int[] keys, Label[] labels) { flushPending(); super.visitLookupSwitchInsn(dflt, keys, labels); }
        @Override public void visitMultiANewArrayInsn(String descriptor, int numDimensions) { flushPending(); super.visitMultiANewArrayInsn(descriptor, numDimensions); }
        @Override public void visitFrame(int type, int numLocal, Object[] local, int numStack, Object[] stack) { flushPending(); super.visitFrame(type, numLocal, local, numStack, stack); }
        @Override public void visitTryCatchBlock(Label start, Label end, Label handler, String type) { flushPending(); super.visitTryCatchBlock(start, end, handler, type); }
        @Override public void visitLineNumber(int line, Label start) { flushPending(); super.visitLineNumber(line, start); }
        @Override public void visitLocalVariable(String name, String descriptor, String signature, Label start, Label end, int index) { flushPending(); super.visitLocalVariable(name, descriptor, signature, start, end, index); }
        @Override public void visitMaxs(int maxStack, int maxLocals) { flushPending(); super.visitMaxs(maxStack, maxLocals); }
        @Override public void visitEnd() { flushPending(); super.visitEnd(); }

        private void flushPending() {
            if (pendingTeleport) {
                super.visitMethodInsn(pendingOpcode, pendingOwner, pendingName, pendingDescriptor, pendingIsInterface);
                pendingTeleport = false;
            }
        }
    }

