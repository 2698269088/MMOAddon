    private static class SchedulerMethodVisitor extends MethodVisitor {

        public SchedulerMethodVisitor(MethodVisitor mv) {
            super(Opcodes.ASM9, mv);
        }

        @Override
        public void visitMethodInsn(int opcode, String owner, String name, String descriptor, boolean isInterface) {
            // Replace Bukkit.getScheduler() -> SchedulerHelper.getScheduler()
            if (opcode == Opcodes.INVOKESTATIC
                    && owner.equals(BUKKIT_CLASS)
                    && name.equals("getScheduler")
                    && descriptor.equals("()L" + BUKKIT_SCHEDULER_CLASS + ";")) {
                schedulerPatchCount++;
                mv.visitMethodInsn(Opcodes.INVOKESTATIC, HELPER_CLASS, "getScheduler",
                        "()L" + BUKKIT_SCHEDULER_CLASS + ";", false);
                return;
            }

            // Patch BukkitRunnable.runXxx(plugin, ...) calls.
            // Subclasses and anonymous inner classes may reference the inherited method
            // through their own type rather than BukkitRunnable, so match by name/descriptor.
            if (opcode == Opcodes.INVOKEVIRTUAL && tryPatchBukkitRunnableCall(name, descriptor)) {
                return;
            }

            // Patch BukkitRunnable.cancel() -> SchedulerHelper.cancelBukkitRunnable(this)
            // on BukkitRunnable itself or on subclasses from any active target plugin.
            if (opcode == Opcodes.INVOKEVIRTUAL
                    && name.equals("cancel")
                    && descriptor.equals("()V")
                    && (owner.equals(BUKKIT_RUNNABLE_CLASS) || isActiveTargetOwner(owner))) {
                mv.visitMethodInsn(Opcodes.INVOKESTATIC, HELPER_CLASS, "cancelBukkitRunnable",
                        "(L" + BUKKIT_RUNNABLE_CLASS + ";)V", false);
                return;
            }

            // Replace Sound.valueOf(String) with SchedulerHelper.resolveSound(String).
            // On Paper 1.20.5+ Sound is an interface and has no valueOf method.
            // The helper throws IllegalArgumentException so callers' try/catch fall back to string keys.
            if (opcode == Opcodes.INVOKESTATIC
                    && owner.equals("org/bukkit/Sound")
                    && name.equals("valueOf")
                    && descriptor.equals("(Ljava/lang/String;)Lorg/bukkit/Sound;")) {
                mv.visitMethodInsn(Opcodes.INVOKESTATIC, HELPER_CLASS, "resolveSound",
                        "(Ljava/lang/String;)Lorg/bukkit/Sound;", false);
                return;
            }

            mv.visitMethodInsn(opcode, owner, name, descriptor, isInterface);
        }

        private boolean tryPatchBukkitRunnableCall(String name, String descriptor) {
            String expectedDescriptor;
            String helperDescriptor;
            switch (name) {
                case "runTask":
                    expectedDescriptor = "(Lorg/bukkit/plugin/Plugin;)Lorg/bukkit/scheduler/BukkitTask;";
                    helperDescriptor = "(L" + BUKKIT_RUNNABLE_CLASS + ";Lorg/bukkit/plugin/Plugin;)Lorg/bukkit/scheduler/BukkitTask;";
                    break;
                case "runTaskLater":
                    expectedDescriptor = "(Lorg/bukkit/plugin/Plugin;J)Lorg/bukkit/scheduler/BukkitTask;";
                    helperDescriptor = "(L" + BUKKIT_RUNNABLE_CLASS + ";Lorg/bukkit/plugin/Plugin;J)Lorg/bukkit/scheduler/BukkitTask;";
                    break;
                case "runTaskTimer":
                    expectedDescriptor = "(Lorg/bukkit/plugin/Plugin;JJ)Lorg/bukkit/scheduler/BukkitTask;";
                    helperDescriptor = "(L" + BUKKIT_RUNNABLE_CLASS + ";Lorg/bukkit/plugin/Plugin;JJ)Lorg/bukkit/scheduler/BukkitTask;";
                    break;
                case "runTaskAsynchronously":
                    expectedDescriptor = "(Lorg/bukkit/plugin/Plugin;)Lorg/bukkit/scheduler/BukkitTask;";
                    helperDescriptor = "(L" + BUKKIT_RUNNABLE_CLASS + ";Lorg/bukkit/plugin/Plugin;)Lorg/bukkit/scheduler/BukkitTask;";
                    break;
                case "runTaskLaterAsynchronously":
                    expectedDescriptor = "(Lorg/bukkit/plugin/Plugin;J)Lorg/bukkit/scheduler/BukkitTask;";
                    helperDescriptor = "(L" + BUKKIT_RUNNABLE_CLASS + ";Lorg/bukkit/plugin/Plugin;J)Lorg/bukkit/scheduler/BukkitTask;";
                    break;
                case "runTaskTimerAsynchronously":
                    expectedDescriptor = "(Lorg/bukkit/plugin/Plugin;JJ)Lorg/bukkit/scheduler/BukkitTask;";
                    helperDescriptor = "(L" + BUKKIT_RUNNABLE_CLASS + ";Lorg/bukkit/plugin/Plugin;JJ)Lorg/bukkit/scheduler/BukkitTask;";
                    break;
                default:
                    return false;
            }

            if (!descriptor.equals(expectedDescriptor)) {
                return false;
            }

            bukkitRunnablePatchCount++;
            mv.visitMethodInsn(Opcodes.INVOKESTATIC, HELPER_CLASS, name, helperDescriptor, false);
            return true;
        }
    }
